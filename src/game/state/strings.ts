export type StateStrings = typeof en;

/** The game UI is English for now. To add a language, write a StateStrings object and register it here. */
const registry: Partial<Record<Language, StateStrings>> = { en };

export const stateStrings = (lang: Language): StateStrings => registry[lang] ?? en;
export const stateLocale = (lang: Language): string => (registry[lang] ? lang : "en");
